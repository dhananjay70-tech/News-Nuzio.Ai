export const t = (key, language = 'en') =>
  translations[language]?.[key] ?? translations.en[key] ?? key;

// Like t(), but substitutes {placeholder} tokens with values from `vars`
// (e.g. tf('generatedAgo', { time: '8m ago' }, language)).
export const tf = (key, vars = {}, language = 'en') =>
  t(key, language).replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ''));
